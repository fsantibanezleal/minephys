"""Generate the knowledge reference pages (spec 000 FR-000-23): one Markdown page per knowledge table.

Usage:  python tools/gen_knowledge_docs.py [--root PATH] [--check]
Writes `<root>/docs/reference/knowledge/<table>.md` for every table of `src/minephys/knowledge/*.yaml` and
`knowledge/share-alike/*.yaml`. A page lists every row in table order (id, quantity, value or range, units, role,
citation with its DOI or URL, page, verification, symbols, notes) and marks every UNVERIFIED row with the word
UNVERIFIED. The pages are deterministic (no time stamp). With `--check` nothing is written and the exit status is 1
when a page is missing or differs from the generated one (stdout names the page). A malformed table exits 2 naming
the file.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import Any

import _knowledge_io as kio

HERE = Path(__file__).resolve().parents[1]
PAGES = Path("docs") / "reference" / "knowledge"


def cell(text: Any) -> str:
    """Markdown table cell: one line, pipes escaped, raw HTML neutralised."""
    return (
        str(text).replace("\\", "\\\\").replace("|", "\\|").replace("<", "&lt;").replace(">", "&gt;").replace("\n", " ")
    )


def fmt_value(row: dict[str, Any]) -> str:
    if "range" in row:
        low, high = row["range"]["min"], row["range"]["max"]
        return f"{fmt_scalar(low)} to {fmt_scalar(high)}"
    return fmt_scalar(row["value"])


def fmt_scalar(value: Any) -> str:
    if isinstance(value, str):
        return value
    if isinstance(value, int):
        return str(value)
    return repr(float(value))


def citation_cell(key: str, bib: dict[str, dict[str, str]]) -> str:
    entry = bib.get(key)
    if not entry:
        return f"`{cell(key)}` (not in references.bib)"
    where = f"DOI {entry['doi']}" if "doi" in entry else entry.get("url", "")
    return f"`{cell(key)}`, {cell(where)}"


def render(tf: kio.TableFile, bib: dict[str, dict[str, str]]) -> str:
    doc = tf.doc
    rows = doc["rows"]
    unverified = sum(1 for r in rows if r.get("verification") == "UNVERIFIED")
    lines = [
        f"# Knowledge table: {cell(doc['title'])}",
        "",
        f"Table `{doc['table']}` (file `{tf.label}`), licence {doc['licence']}. Generated by `tools/gen_knowledge_docs.py`; do not edit.",
        "",
        f"Rows: {len(rows)}. Rows flagged UNVERIFIED: {unverified}.",
        "",
        "| Row id | Quantity | Value or range | Units | Role | Citation | Page | Verification | Symbol |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    notes: list[str] = []
    for r in rows:
        symbols = "<br>".join(f"`{cell(s)}`" for s in kio.symbols_of(r))
        status = "UNVERIFIED" if r["verification"] == "UNVERIFIED" else f"verified ({r['verified_on']})"
        lines.append(
            f"| `{r['id']}` | {cell(r['quantity'])} | {cell(fmt_value(r))} | {cell(r['units'])} | {r['role']} | "
            f"{citation_cell(r['citation'], bib)} | {cell(r['page'])} | {status} | {symbols} |"
        )
        if r.get("notes"):
            notes.append(f"- `{r['id']}`: {cell(r['notes'])}")
    if notes:
        lines += ["", "## Notes", "", *notes]
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", type=Path, default=HERE)
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if a page is missing or differs")
    args = ap.parse_args(argv[1:])
    root = args.root.resolve()
    bib, _ = kio.read_bibliography(root)
    files = [kio.read_table(tf) for tf in kio.table_files(root)]
    failed = False
    for tf in files:
        problems = tf.errors + kio.validate_table(tf)
        if problems:
            failed = True
            print(f"{tf.label}: cannot generate a page:")
            for line in problems:
                print(f"  {line}")
    if failed:
        return 2
    differing = 0
    for tf in files:
        page = root / PAGES / f"{tf.stem}.md"
        text = render(tf, bib)
        if args.check:
            current = page.read_bytes().replace(b"\r\n", b"\n") if page.is_file() else None
            if current != text.encode("utf-8"):
                differing += 1
                print(f"{page.relative_to(root).as_posix()}: {'missing' if current is None else 'differs from the generated page'}")
        else:
            page.parent.mkdir(parents=True, exist_ok=True)
            page.write_bytes(text.encode("utf-8"))
    if args.check:
        print("KNOWLEDGE PAGES OK" if not differing else f"KNOWLEDGE PAGES STALE ({differing})")
        return 1 if differing else 0
    print(f"wrote {len(files)} page(s) under {PAGES.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
