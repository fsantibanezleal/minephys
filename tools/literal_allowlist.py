"""Generate or check `tools/literal_allowlist.txt` (spec 000 FR-000-19): every float literal under `src/minephys/`.

Dry run by default: prints the entries and exits 0 when the committed file is current, 1 when it differs.
`--write` rewrites the file. Entries are structural constants, decimal SI prefixes, exact mathematical constants and
numerical tolerances; any other float literal is a physical or empirical constant and must be a knowledge row, so
the tool exits 2 and lists it.
"""

from __future__ import annotations

import argparse
import ast
import math
import sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "minephys"
ALLOWLIST = ROOT / "tools" / "literal_allowlist.txt"
HEADER = (
    "# Float literals allowed under src/minephys/ (spec 000 FR-000-19). Generated by tools/literal_allowlist.py;\n"
    "# one entry per line: <literal> | <reason>. Physical and empirical constants live in knowledge rows instead.\n"
)


def category(v: float) -> str | None:
    """The permitted category of a literal, or None when it would have to be a knowledge row."""
    f = Fraction(v).limit_denominator(10)
    if v == 0.0 or (abs(f.numerator) <= 10 and f.denominator <= 10 and math.isclose(float(f), v, rel_tol=1e-15)):
        return "structural constant of a formula (small exact integer or simple fraction)"
    a = abs(v)
    if any(math.isclose(a, 10.0**k, rel_tol=1e-15) for k in [*range(-24, 25, 3), -2, -1, 1, 2]):
        return "decimal SI prefix or power of ten used as a numerical guard"
    for const in (math.pi, math.e, math.sqrt(2.0)):
        for p in range(1, 11):
            for q in range(1, 11):
                if math.isclose(a, const * p / q, rel_tol=4e-16, abs_tol=0.0):
                    return "exact mathematical constant"
    if 0.0 < a <= 1e-6:
        return "numerical tolerance or tiny guard"
    return None


def scan() -> dict[float, list[str]]:
    found: dict[float, list[str]] = {}
    for path in sorted(SRC.rglob("*.py")):
        for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
            if isinstance(node, ast.Constant) and isinstance(node.value, float):
                found.setdefault(node.value, []).append(f"{path.relative_to(ROOT).as_posix()}:{node.lineno}")
    return found


def render(found: dict[float, list[str]]) -> tuple[str, list[tuple[float, list[str]]]]:
    lines, rejected = [], []
    for value in sorted(found):
        reason = category(value)
        if reason is None:
            rejected.append((value, found[value]))
        else:
            lines.append(f"{value!r} | {reason}\n")
    return HEADER + "".join(lines), rejected


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="rewrite tools/literal_allowlist.txt")
    args = parser.parse_args(argv)
    text, rejected = render(scan())
    if rejected:
        for value, where in rejected:
            print(f"not allowlistable (use a knowledge row): {value!r} at {', '.join(where[:3])}", file=sys.stderr)
        return 2
    if args.write:
        ALLOWLIST.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {ALLOWLIST.relative_to(ROOT).as_posix()}")
        return 0
    current = ALLOWLIST.read_text(encoding="utf-8") if ALLOWLIST.is_file() else ""
    print(text, end="")
    return 0 if current == text else 1


if __name__ == "__main__":
    sys.exit(main())
